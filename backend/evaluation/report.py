"""Write ``docs/evaluation/BASELINE.md`` and the labelled findings it was computed from.

    uv run python -m evaluation.report        # make eval-baseline

The output holds no clock time or random state beyond the fixed seed, so a rerun on the
same fixtures is byte-identical (expansion plan §7).
"""

from __future__ import annotations

import csv
import io
import json
from collections.abc import Callable, Sequence
from dataclasses import astuple, fields
from pathlib import Path

from riskgraph.modules.risk import MODEL_VERSION

from evaluation.baselines import METHODS, rank
from evaluation.metrics import (
    BOOTSTRAP_RESAMPLES,
    BOOTSTRAP_SEED,
    Estimate,
    average_precision,
    bootstrap,
    effort_at,
    ndcg_at,
    precision_at,
    recall_at,
)
from evaluation.record import FIXTURES, INTEL
from evaluation.run import Row, collect
from evaluation.scenarios import SCENARIOS

OUT_DIR = Path(__file__).resolve().parents[2] / "docs" / "evaluation"

Metric = Callable[[Sequence[bool]], float | None]
METRICS: dict[str, Metric] = {
    "P@5": lambda r: precision_at(r, 5),
    "P@10": lambda r: precision_at(r, 10),
    "R@5": lambda r: recall_at(r, 5),
    "R@10": lambda r: recall_at(r, 10),
    "nDCG@5": lambda r: ndcg_at(r, 5),
    "nDCG@10": lambda r: ndcg_at(r, 10),
    "AP": average_precision,
    "E90": lambda r: _float(effort_at(r)),
}


def _float(v: int | None) -> float | None:
    return float(v) if v is not None else None


def _labels(rows: Sequence[Row], method: str) -> list[bool]:
    return [r.important for r in rank(rows, method)]


def _statistic(method: str, metric: Metric) -> Callable[[Sequence[Row]], float | None]:
    return lambda sample: metric(_labels(sample, method))


def _fmt(v: float | None, places: int = 3) -> str:
    return "n/a" if v is None else f"{v:.{places}f}"


def _cell(e: Estimate, name: str) -> str:
    places = 0 if name == "E90" else 3
    if e.low is None or e.high is None:
        return _fmt(e.value, places)
    return f"{_fmt(e.value, places)} [{_fmt(e.low, places)}, {_fmt(e.high, places)}]"


def _versions() -> str:
    scanners = sorted(
        {f"{p.parent.parent.name} {p.parent.name}" for p in FIXTURES.glob("*/*/*/report.json")}
    )
    return ", ".join(scanners)


def render(rows: Sequence[Row]) -> str:
    intel = json.loads(INTEL.read_text())
    lines = [
        "# RiskGraph baseline (expansion phase X0)",
        "",
        "Generated by `make eval-baseline` (`backend/evaluation/report.py`). Do not edit by hand.",
        "",
        f"- Risk model: `{MODEL_VERSION}`.",
        f"- Scanner reports: recorded once with the pinned images ({_versions()}).",
        f"- EPSS/KEV: frozen snapshot from {intel['source']}, fetched {intel['fetched_at']}.",
        f"- Confidence intervals: 95 % percentile bootstrap over findings, "
        f"{BOOTSTRAP_RESAMPLES} resamples, seed {BOOTSTRAP_SEED}, the same draws for every "
        "method.",
        "- Labels: by construction from `backend/evaluation/scenarios.py`, written before any "
        "ranking was computed (rubric in blueprint §26.3). Per-finding labels and rationale: "
        "`baseline_findings.csv`.",
        "- Not in this set: authorization findings (X5); they are labelled with the X6 "
        "scenarios (`OUTSIDE_X0` in `backend/evaluation/run.py`).",
        "",
        "## Dataset",
        "",
        "| Scenario | Findings | Important | Defaulted label |",
        "|---|---:|---:|---:|",
    ]
    for name in sorted(SCENARIOS):
        sub = [r for r in rows if r.scenario == name]
        lines.append(
            f"| {name} | {len(sub)} | {sum(r.important for r in sub)} "
            f"| {sum(r.defaulted for r in sub)} |"
        )
    lines += [
        f"| **All** | **{len(rows)}** | **{sum(r.important for r in rows)}** "
        f"| **{sum(r.defaulted for r in rows)}** |",
        "",
        "## Pooled ranking (primary)",
        "",
        "All scenarios' findings ranked as one list, as an analyst triaging several "
        "repositories would see them. E90 is the number of findings read, from the top, to "
        "see 90 % of the important ones (lower is better).",
        "",
        "| Method | " + " | ".join(METRICS) + " |",
        "|---|" + "---|" * len(METRICS),
    ]
    for method in METHODS:
        cells = [
            _cell(bootstrap(rows, _statistic(method, metric)), name)
            for name, metric in METRICS.items()
        ]
        lines.append(f"| {method} | " + " | ".join(cells) + " |")

    scored = [n for n in sorted(SCENARIOS) if any(r.important for r in rows if r.scenario == n)]
    lines += [
        "",
        "## Per scenario",
        "",
        "Each scenario ranked on its own (point values; too few findings per scenario for "
        "useful intervals). Scenarios with no important finding have no recall-based "
        f"metric. MAP is the mean AP over the scenarios that have one ({', '.join(scored)}).",
        "",
        "| Method | Scenario | P@5 | nDCG@10 | AP |",
        "|---|---|---:|---:|---:|",
    ]
    per_method: dict[str, list[str]] = {}
    for method in METHODS:
        aps: list[float] = []
        rows_out: list[str] = []
        for name in sorted(SCENARIOS):
            rel = _labels([r for r in rows if r.scenario == name], method)
            ap = average_precision(rel)
            if ap is not None:
                aps.append(ap)
            rows_out.append(f"| {name} | {_fmt(precision_at(rel, 5))} | {_fmt(ndcg_at(rel, 10))} ")
            lines.append(f"| {method} {rows_out[-1]}| {_fmt(ap)} |")
        lines.append(f"| {method} | **MAP** | | | **{_fmt(sum(aps) / len(aps))}** |")
        per_method[method] = rows_out
    if len({tuple(c) for c in per_method.values()}) == 1:
        lines += [
            "",
            "Every method ties on every scenario: within one small repository even CVSS "
            "alone puts the important findings first. The pooled differences above come "
            "entirely from comparing findings across repositories with different context.",
        ]

    lines += ["", "## Top 10 of the pooled ranking", ""]
    for method in METHODS:
        lines += [
            f"**{method}**",
            "",
            "| # | Important | Scenario | Finding |",
            "|---:|---|---|---|",
        ]
        for i, r in enumerate(rank(rows, method)[:10], start=1):
            what = r.vulnerability_id or r.rule_id
            where = r.package or r.file
            lines.append(
                f"| {i} | {'yes' if r.important else 'no'} | {r.scenario} "
                f"| {r.source_type} `{what}` ({where}) |"
            )
        lines.append("")

    neg = {n: sum(not r.important for r in rows if r.scenario == n) for n in sorted(SCENARIOS)}
    top_neg = max(neg, key=lambda n: neg[n])
    lines += [
        "## Reading these numbers",
        "",
        "- Five synthetic scenarios written by the model's author: construct bias is the main "
        "threat to validity (blueprint §26.6). The positive rate is "
        f"{sum(r.important for r in rows) / len(rows):.1%}, below the 15-25 % the blueprint "
        f"aims for, and {top_neg} contributes {neg[top_neg]} of the {sum(neg.values())} "
        "negatives.",
        "- Scenario E's SSRF is reported by two Semgrep rules on the same line; both are "
        "labelled important, so it counts twice.",
        "- No KEV entry appears in the snapshot for these CVEs, so KEV does not influence "
        "any method here."
        if not intel["kev"]
        else "- Some CVEs are in KEV; M4 uses KEV in E, M1 and M2 do not.",
        "- This is the baseline later phases must beat; the numbers are not tuned. The "
        "pre-registered targets are in `docs/proposals/EXPANSION_A-D.md` §6.",
        "",
    ]
    return "\n".join(lines)


def findings_csv(rows: Sequence[Row]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow([f.name for f in fields(Row)])
    for r in rows:
        w.writerow(astuple(r))
    return buf.getvalue()


def main() -> None:
    rows = collect()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "BASELINE.md").write_text(render(rows), encoding="utf-8")
    (OUT_DIR / "baseline_findings.csv").write_text(findings_csv(rows), encoding="utf-8")
    print(f"wrote {OUT_DIR / 'BASELINE.md'} ({len(rows)} findings)")  # noqa: T201


if __name__ == "__main__":
    main()
